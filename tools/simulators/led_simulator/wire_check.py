#!/usr/bin/env python3
"""Prove the strip accepts exactly what the phone now sends it.

`parity_check.py` proves the *rendering* is identical. This proves the other half of the
chain: that the firmware's own `RAMP:` and `CFG:scol=` parsers accept the payloads the app
derives from the theme, byte for byte, and turn them into the table the app intended.

That matters because the theme logic lives in the phone, not the strip. The Nano has no
idea what a "scheme" is: it renders the ramp and the shift color it was last given. So the
only thing that can silently break when the app changes is the wire format - a case change,
a stop count, a length - and a parser that rejects the payload fails *quietly*: the strip
keeps its old table and looks like the theme did nothing.

The parser blocks are extracted from `arduino/src/main.cpp` by brace matching and compiled
with the firmware's own constants, so this is the strip's code, not a transcription of it.

    python wire_check.py

Needs a C++ compiler (MSVC via vswhere, g++ on PATH, or set MX5_CL). Without one it reports SKIPPED and
exits 0.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from typing import List, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

sys.path.insert(0, HERE)

import app_palette  # noqa: E402
import parity_check  # noqa: E402


def read_main() -> str:
    with open(parity_check.MAIN_CPP, encoding="utf-8") as handle:
        return handle.read()


def extract_branch(source: str, needle: str) -> str:
    """The whole `if (...) { ... }` whose condition starts with `needle`, verbatim.

    Sliced from the `if`, not from the start of the line, because both branches follow an
    `else` - from the line start this would yield `else if (...) {...}`, which does not
    compile on its own.
    """
    start = source.find(needle)
    if start < 0:
        raise SystemExit("could not find %r in main.cpp" % needle)
    brace = source.find("{", start)
    if brace < 0:
        raise SystemExit("no block after %r in main.cpp" % needle)
    depth = 0
    for index in range(brace, len(source)):
        char = source[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return source[start:index + 1]
    raise SystemExit("unbalanced braces after %r in main.cpp" % needle)


def grab(style: str, pattern: str, source: str) -> str:
    match = re.search(pattern, source, re.M | re.S)
    if not match:
        raise SystemExit("could not find %s in main.cpp" % style)
    return match.group(1).strip()


def build_harness(source: str) -> str:
    stop_count = parity_check.extract_define(source, "RAMP_STOP_COUNT")
    struct_body = grab("struct RampStop", r"struct RampStop\s*\{(.*?)\};", source)
    stops = parity_check.extract_initializer(source, "rampStops[RAMP_STOP_COUNT]")
    rpm_full = grab("rpmFull", r"uint16_t\s+rpmFull\s*=\s*(\d+);", source)
    shift_match = re.search(r"uint8_t\s+shiftR\s*=\s*(\d+)\s*,\s*shiftG\s*=\s*(\d+)\s*,"
                            r"\s*shiftB\s*=\s*(\d+)\s*;", source)
    if not shift_match:
        raise SystemExit("could not find the shift color defaults in main.cpp")
    shift_parts = list(shift_match.groups())
    ramp_branch = extract_branch(source, 'if (strncmp(cmdBuffer, "RAMP:", 5) == 0)')
    scol_branch = extract_branch(source, 'if (strncmp(p, "scol=", 5) == 0)')

    return r"""
// Generated by wire_check.py from arduino/src/main.cpp. Do not edit.
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <string>
#include <iostream>

#define RAMP_STOP_COUNT %(stop_count)s
#define F(x) x

// The only Arduino bit the parsers touch: the replies they print.
struct CmdOut {
    void print(const char*) const {}
    void println(const char*) const {}
    void println() const {}
};
static CmdOut cmdSerial;

struct RampStop { %(struct_body)s };

static RampStop rampStops[RAMP_STOP_COUNT] = %(stops)s;
static uint8_t  rampStopCount = RAMP_STOP_COUNT;
static uint16_t rpmFull = %(rpm_full)s;
static uint16_t lastRenderedRPM = 0;
static uint8_t  shiftR = %(sr)s, shiftG = %(sg)s, shiftB = %(sb)s;

// The firmware's own parsing code, sliced out of handleCommand().
static void applyRamp(char* cmdBuffer) {
    %(ramp_branch)s
}

static void applyColour(char* p) {
    %(scol_branch)s
}

static void dump() {
    printf("count=%%d full=%%d scol=%%02x%%02x%%02x table=",
           (int)rampStopCount, (int)rpmFull, shiftR, shiftG, shiftB);
    for (int i = 0; i < rampStopCount; i++) {
        printf("%%s%%d:%%02x%%02x%%02x", i ? "," : "",
               (int)rampStops[i].rpm, rampStops[i].r, rampStops[i].g, rampStops[i].b);
    }
    printf("\n");
}

int main() {
    std::string line;
    while (std::getline(std::cin, line)) {
        if (line.empty() || line[0] == '#') {
            continue;
        }
        char buffer[160];
        strncpy(buffer, line.c_str(), sizeof(buffer) - 1);
        buffer[sizeof(buffer) - 1] = 0;

        if (strncmp(buffer, "RAMP:", 5) == 0) {
            applyRamp(buffer);
        } else if (strncmp(buffer, "CFG:", 4) == 0) {
            char* p = buffer + 4;
            if (strncmp(p, "scol=", 5) == 0) {
                applyColour(p);
            }
        }
        dump();
    }
    return 0;
}
""" % {
        "stop_count": stop_count,
        "struct_body": struct_body,
        "stops": stops,
        "rpm_full": rpm_full,
        "sr": shift_parts[0],
        "sg": shift_parts[1],
        "sb": shift_parts[2],
        "ramp_branch": ramp_branch,
        "scol_branch": scol_branch,
    }


def compile_harness(work: str, compiler: str) -> str:
    return parity_check._compile(work, compiler, "wire.cpp", "wire")


def expected_ramp(scheme_id: str, dark: bool) -> str:
    """The `RAMP:` payload the app builds - uppercase, exactly as `MainActivity.hex()`."""
    pal = app_palette.palette(scheme_id, dark)
    return ",".join("%d:%02x%02x%02x" % (rpm, rgb[0], rgb[1], rgb[2])
                    for rpm, rgb in app_palette.ramp_for(pal)).upper()


def expected_shift(scheme_id: str, dark: bool) -> str:
    return app_palette.shift_text(scheme_id, dark).upper()


def run(exe: str, lines: List[str]) -> List[str]:
    done = subprocess.run([exe], input="\n".join(lines) + "\n",
                          capture_output=True, text=True, timeout=120)
    if done.returncode != 0:
        raise SystemExit("harness failed:\n%s" % done.stderr)
    return [line.strip() for line in done.stdout.splitlines() if line.strip()]


def check(rows: List[Tuple[str, str, str, str]]) -> Tuple[List[str], int, int]:
    """Feed every scheme's ramp and shift color through the firmware's parsers."""
    problems: List[str] = []
    lines, want = [], []
    for scheme_id, mode, ramp, shift in rows:
        lines.append("RAMP:" + ramp)
        lines.append("CFG:scol=" + shift)
        want.append((scheme_id, mode, ramp, shift))

    # Two payloads per scheme: the ramp reply, then the color reply.
    out = run(EXE[0], lines)
    if len(out) != 2 * len(want):
        problems.append("expected %d replies, got %d" % (2 * len(want), len(out)))
        return problems, 0, 0

    checked = 0
    for index, (scheme_id, mode, ramp, shift) in enumerate(want):
        dump = out[2 * index]
        colours = out[2 * index + 1]
        where = "%s/%s" % (scheme_id, mode)

        count = int(re.search(r"count=(\d+)", dump).group(1))
        full = int(re.search(r"full=(\d+)", dump).group(1))
        table = re.search(r"table=(.*)$", dump).group(1)
        stops = ramp.split(",")
        if count != len(stops):
            problems.append("%s: strip kept %d stops, app sent %d" % (where, count, len(stops)))
        elif table.lower() != ramp.lower():
            problems.append("%s: strip parsed\n    %s\n  app sent\n    %s" % (where, table, ramp))
        if full != int(stops[-1].split(":")[0]):
            problems.append("%s: strip's full-ramp rpm is %d, app's last stop is %s"
                            % (where, full, stops[-1].split(":")[0]))

        got_shift = re.search(r"scol=([0-9a-f]{6})", colours).group(1)
        if got_shift.upper() != shift:
            problems.append("%s: strip's shift color is %s, app sent %s"
                            % (where, got_shift, shift))
        checked += 1
    return problems, checked, len(out)


def check_rejects(boot_table: str) -> List[str]:
    """A malformed payload must leave the live ramp exactly as it was.

    The strip parses a `RAMP:` line part by part, so the interesting question is not only
    whether a bad line is rejected but whether it *half applied* first: a reused stop table
    would show up as a mixture of the old and new rows, which looks like a working command
    that did something strange.
    """
    problems: List[str] = []
    cases = [
        ("RAMP:0:2ecccc", "a one-stop ramp"),
        ("RAMP:0:2ecc", "a truncated color"),
        ("RAMP:0:2ecccc,", "a trailing comma with no second stop"),
        ("CFG:scol=6ddb", "a truncated shift color"),
    ]
    lines = [command for command, _why in cases]
    out = run(EXE[0], lines)
    for index, (command, why) in enumerate(cases):
        dump = out[index]
        count = int(re.search(r"count=(\d+)", dump).group(1))
        full = int(re.search(r"full=(\d+)", dump).group(1))
        table = re.search(r"table=(.*)$", dump).group(1)
        if command.startswith("CFG:scol="):
            got = re.search(r"scol=([0-9a-f]{6})", dump).group(1)
            if got != "ff0000":
                problems.append("%s: %s changed the shift color to %s"
                                % (why, command, got))
        elif count != 6 or full != 6800 or table != boot_table:
            problems.append("%s: %s changed the ramp to count=%d full=%d %s"
                            % (why, command, count, full, table))
    return problems


EXE = [""]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--keep", action="store_true", help="keep the generated sources")
    args = parser.parse_args()

    compiler = parity_check.find_compiler()
    if not compiler:
        print("SKIPPED: no C++ compiler found (MSVC, g++ on PATH, or set MX5_CL)")
        return 0
    print("compiler:", compiler)

    work = tempfile.mkdtemp(prefix="mx5-wire-")
    try:
        with open(os.path.join(work, "wire.cpp"), "w", encoding="utf-8") as handle:
            handle.write(build_harness(read_main()))
        EXE[0] = compile_harness(work, compiler)

        rows = [(ident, "dark" if dark else "light",
                 expected_ramp(ident, dark), expected_shift(ident, dark))
                for ident, _name, _a, _b in app_palette.SCHEMES
                for dark in (True, False)]
        problems, checked, replies = check(rows)

        # The defaults must still be the firmware's own, or "ROYGBIV" in the simulator would
        # not mean what the strip does before the phone ever connects.
        boot = run(EXE[0], ["PING"])[0]
        boot_table = re.search(r"table=(.*)$", boot).group(1)
        if "count=6" not in boot or "scol=ff0000" not in boot or "full=6800" not in boot:
            problems.append("boot defaults are not the documented 6-stop ramp, red flash "
                            "and 6800 full rpm: %s" % boot)

        problems.extend(check_rejects(boot_table))

        print("schemes: %d   payloads compared: %d   replies: %d"
              % (len(app_palette.SCHEMES) * 2, checked * 2, replies))
        if not problems:
            print("WIRE OK - the strip parses exactly what the phone sends")
            return 0
        for problem in problems:
            print("MISMATCH", problem)
        return 1
    finally:
        if args.keep:
            print("generated files kept in", work)
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
