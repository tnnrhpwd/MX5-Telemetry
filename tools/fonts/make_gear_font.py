#!/usr/bin/env python3
"""Bake the ESP32 large-gear glyph masks from a real typeface.

The round display draws a single big gear character (R, N, C, S, 0-9, -). Rather
than hand-drawing strokes, this renders those characters from Arimo -- the SIL
Open Font License 1.1 design that is metric-compatible with Arial -- and stores
them as 8-bit coverage masks cropped to their ink bounds.

Arial itself is Monotype-proprietary and cannot be embedded, but Arimo's
letterforms and spacing are drawn to the same widths, so the result is the same
typeface the user was asking for.

Output: display/src/ui_core/gear_font.h (committed; the firmware build needs no
font file and no font engine).

Usage:
    python tools/fonts/make_gear_font.py --font Arimo-var.ttf [--preview out.png]

Get the font from https://github.com/google/fonts/tree/main/ofl/arimo
(OFL.txt next to it must stay with the generated header).
"""

from __future__ import annotations

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

# Must match GEAR_GLYPH_CELL_W/H in display/src/ui_core/ui_core.cpp.
CELL_W = 46
CELL_H = 66
CAP_HEIGHT = 50          # caps and digits, px
SUPERSAMPLE = 4

CHARS = "0123456789RNCSG-"
DEFAULT_WEIGHT = 700     # Arial-bold weight reads best on a small round panel

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_HEADER = os.path.join(REPO, "display", "src", "ui_core", "gear_font.h")


def load_font(path: str, size: float, weight: int) -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(path, size)
    try:
        font.set_variation_by_axes([weight])
    except Exception:  # static instance, no wght axis
        pass
    return font


def cap_height(path: str, weight: int) -> float:
    probe = load_font(path, 400, weight)
    box = probe.getbbox("H")
    return float(box[3] - box[1])


def render_glyph(path: str, ch: str, size: float, weight: int, baseline: int,
                 xscale: float = 1.0, check: bool = True):
    """Returns (left, top, width, height, alpha_bytes) in cell coordinates."""
    big = load_font(path, size * SUPERSAMPLE, weight)
    ascent, descent = big.getmetrics()
    pad = 8
    advance = big.getlength(ch)
    canvas_w = int(advance) + 2 * pad + SUPERSAMPLE * 2
    canvas_h = ascent + descent + 2 * pad

    canvas = Image.new("L", (canvas_w, canvas_h), 0)
    ImageDraw.Draw(canvas).text((pad, pad), ch, font=big, fill=255)

    box = canvas.getbbox()
    if box is None:
        raise SystemExit(f"glyph {ch!r} rendered empty")

    ink = canvas.crop(box)
    ink = ink.resize(
        (max(1, round(ink.width / SUPERSAMPLE * xscale)), max(1, round(ink.height / SUPERSAMPLE))),
        Image.BOX,
    )

    # Coordinates are measured at supersampled scale and converted down.
    pen_x = (CELL_W - advance / SUPERSAMPLE * xscale) / 2.0
    ink_left = pen_x + (box[0] - pad) / SUPERSAMPLE * xscale
    ink_top_rel_baseline = (box[1] - (pad + ascent)) / SUPERSAMPLE

    left = int(round(ink_left))
    top = int(round(baseline + ink_top_rel_baseline))

    if check and (left < 0 or top < 0 or left + ink.width > CELL_W or top + ink.height > CELL_H):
        raise ValueError(
            f"glyph {ch!r} does not fit the {CELL_W}x{CELL_H} cell: "
            f"left={left} top={top} {ink.width}x{ink.height}"
        )

    return left, top, ink.width, ink.height, ink.tobytes()


def build_glyphs(path: str, weight: int, cap: int, xscale: float = 1.0, check: bool = True):
    size = 400.0 * cap / cap_height(path, weight)
    baseline = (CELL_H + cap) // 2
    return [(ch,) + render_glyph(path, ch, size, weight, baseline, xscale, check) for ch in CHARS]


def emit_header(weight: int, cap: int, glyphs, font_name: str) -> str:
    out = []
    w = out.append
    w("// AUTO-GENERATED by tools/fonts/make_gear_font.py -- do not edit by hand.")
    w("//")
    w(f"// Large-gear typeface: {font_name} {weight}, rasterised from the original")
    w("// outline font to 8-bit coverage masks cropped to their ink bounds.")
    w("//")
    w("// Arimo is SIL Open Font License 1.1 and metric-compatible with Arial, so")
    w("// these are the letterforms a reader of that typeface expects. Arial itself")
    w("// is proprietary and is not embedded here. The licence text must be")
    w("// distributed with the firmware: see Arimo-OFL.txt beside this header.")
    w("//")
    w(f"// Cell {CELL_W}x{CELL_H} px, cap height {cap} px, baseline y={(CELL_H + cap) // 2}.")
    w("#pragma once")
    w("")
    w("#include <stdint.h>")
    w("")
    w(f"#define GEAR_GLYPH_CELL_W {CELL_W}")
    w(f"#define GEAR_GLYPH_CELL_H {CELL_H}")
    w("")
    w("struct GearGlyphBitmap {")
    w("    char           ch;")
    w("    uint8_t        left;   // x of the first column inside the cell")
    w("    uint8_t        top;    // y of the first row inside the cell")
    w("    uint8_t        w;")
    w("    uint8_t        h;")
    w("    const uint8_t* alpha;  // w*h coverage, row major, 0..255")
    w("};")
    w("")

    for ch, left, top, gw, gh, alpha in glyphs:
        name = "GEAR_GLYPH_%s" % ({"-": "DASH"}.get(ch, ch))
        w(f"static const uint8_t {name}_ALPHA[{gw * gh}] = {{")
        for row in range(gh):
            chunk = alpha[row * gw:(row + 1) * gw]
            w("    " + ",".join("%d" % v for v in chunk) + ",")
        w("};")
        w("")

    w("static const GearGlyphBitmap GEAR_GLYPHS[] = {")
    for ch, left, top, gw, gh, _alpha in glyphs:
        name = "GEAR_GLYPH_%s" % ({"-": "DASH"}.get(ch, ch))
        chlit = "'-'" if ch == "-" else "'%s'" % ch
        w(f"    {{ {chlit}, {left}, {top}, {gw}, {gh}, {name}_ALPHA }},")
    w("};")
    w("")
    w("#define GEAR_GLYPH_COUNT (sizeof(GEAR_GLYPHS) / sizeof(GEAR_GLYPHS[0]))")
    w("")
    return "\n".join(out) + "\n"


def write_preview(glyphs, path: str, bg=(16, 16, 20), fg=(232, 232, 236)) -> None:
    zoom = 4
    cols = len(glyphs)
    sheet = Image.new("RGB", (cols * (CELL_W + 4) * zoom, (CELL_H + 8) * zoom), bg)
    for i, (_ch, left, top, gw, gh, alpha) in enumerate(glyphs):
        mask = Image.frombytes("L", (gw, gh), alpha)
        cell = Image.new("RGB", (CELL_W, CELL_H), bg)
        cell.paste(Image.new("RGB", (gw, gh), fg), (left, top), mask)
        sheet.paste(cell.resize((CELL_W * zoom, CELL_H * zoom), Image.NEAREST),
                    (i * (CELL_W + 4) * zoom, 4 * zoom))
    sheet.save(path)
    print(f"preview -> {path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True, help="path to Arimo[wght].ttf")
    ap.add_argument("--weight", type=int, default=DEFAULT_WEIGHT)
    ap.add_argument("--preview", help="write a PNG contact sheet")
    ap.add_argument("--out", default=OUT_HEADER)
    args = ap.parse_args()

    # Bold letterforms are wider than the stroke-drawn glyphs they replace: at the
    # nominal cap height the widest ('R', 'C') overflow the 46 px cell. Rather
    # than shrink the digits, condense horizontally just enough to fit -- the
    # small amount needed is what makes a HUD face look like a HUD face, and it
    # keeps the full stroke height on the panel.
    widest = max(g[3] for g in build_glyphs(args.font, args.weight, CAP_HEIGHT, check=False))
    xscale = min(1.0, (CELL_W - 2) / float(widest))
    glyphs = build_glyphs(args.font, args.weight, CAP_HEIGHT, xscale)
    cap = CAP_HEIGHT
    print(f"cap height {cap} px, em {400.0 * cap / cap_height(args.font, args.weight):.2f} px, "
          f"x-scale {xscale:.3f}")

    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(emit_header(args.weight, cap, glyphs, "Arimo"))

    total = sum(g[3] * g[4] for g in glyphs)
    print(f"{len(glyphs)} glyphs, {total} bytes of coverage -> {args.out}")

    if args.preview:
        write_preview(glyphs, args.preview)


if __name__ == "__main__":
    main()
